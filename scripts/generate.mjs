import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';

function buildRoutesSource(contractPath) {
  const spec = JSON.parse(fs.readFileSync(contractPath, 'utf8'));
  const paramsByRef = spec.components?.parameters ?? {};
  const resolveParam = (param) => {
    if (param && typeof param.$ref === 'string' && param.$ref.startsWith('#/components/parameters/')) {
      const key = param.$ref.slice('#/components/parameters/'.length);
      const target = paramsByRef[key];
      assert(target, `Missing parameter component: ${param.$ref}`);
      return target;
    }
    return param;
  };

  const methods = ['get', 'post', 'put', 'patch', 'delete', 'options', 'head', 'trace'];
  const entries = [];
  for (const route of Object.keys(spec.paths ?? {}).sort()) {
    const item = spec.paths[route];
    for (const method of methods) {
      const op = item?.[method];
      if (!op) continue;
      const resolved = (op.parameters ?? []).map(resolveParam);
      const queryParams = resolved.filter((p) => p.in === 'query').map((p) => p.name).sort();
      const idempotent = resolved.some((p) => p.in === 'header' && p.name === 'Idempotency-Key' && p.required);
      entries.push({ pattern: `${method.toUpperCase()} ${route}`, queryParams, idempotent });
    }
  }

  const lines = [
    '// Code generated by scripts/generate.mjs from contracts/open-platform.openapi.json; DO NOT EDIT.',
    'package httpapi',
    '',
    'type routeSpec struct {',
    '\tqueryParams []string',
    '\tidempotent  bool',
    '}',
    '',
    'var contractRoutes = map[string]routeSpec{',
  ];
  for (const entry of entries) {
    const q = entry.queryParams.map((name) => JSON.stringify(name)).join(', ');
    lines.push(`\t${JSON.stringify(entry.pattern)}: {queryParams: []string{${q}}, idempotent: ${entry.idempotent}},`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

const check = process.argv.includes('--check');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'stuhelper-open-platform-generate-'));
try {
  fs.mkdirSync('sdk', { recursive: true });
  fs.mkdirSync('httpapi', { recursive: true });
  const goOutput = check ? path.join(temporary, 'open-platform.gen.go') : 'sdk/open-platform.gen.go';
  const tsOutput = check ? path.join(temporary, 'open-platform.gen.ts') : 'sdk/open-platform.gen.ts';
  const routesOutput = check ? path.join(temporary, 'routes.gen.go') : 'httpapi/routes.gen.go';
  execFileSync('go', ['run', 'github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.0', '-generate', 'types,client,std-http-server', '-package', 'sdk', '-o', goOutput, 'contracts/open-platform.openapi.json'], { stdio: 'inherit' });
  fs.writeFileSync(routesOutput, buildRoutesSource('contracts/open-platform.openapi.json'));
  execFileSync('gofmt', ['-w', goOutput, routesOutput], { stdio: 'inherit' });
  execFileSync('pnpm', ['exec', 'openapi-typescript', 'contracts/open-platform.openapi.json', '-o', tsOutput], { stdio: 'inherit' });
  if (check) {
    for (const [expected, actual] of [
      ['sdk/open-platform.gen.go', goOutput],
      ['sdk/open-platform.gen.ts', tsOutput],
      ['httpapi/routes.gen.go', routesOutput],
    ]) {
      assert.equal(fs.readFileSync(expected, 'utf8'), fs.readFileSync(actual, 'utf8'), `Generated contract differs: ${expected}`);
    }
  }
} finally {
  fs.rmSync(temporary, { recursive: true, force: true });
}
